export function getLabStats() {
  const all = LAB_ORDERS;
  return {
    totalToday: all.filter((o) =>
      o.orderedOn.startsWith("2026-09-13")
    ).length,
    pending: all.filter((o) => o.status === "PENDING").length,
    collected: all.filter((o) => o.status === "SAMPLE_COLLECTED").length,
    processing: all.filter((o) => o.status === "PROCESSING").length,
    ready: all.filter((o) => o.status === "READY").length,
    published: all.filter((o) => o.status === "PUBLISHED").length,
    urgent: all.filter(
      (o) => o.priority === "URGENT" && o.status !== "PUBLISHED"
    ).length,
  };
}

export function getOrderById(id) {
  return LAB_ORDERS.find((o) => o.id === Number(id)) || null;
}

